package fr.citoyende2027.core.database

import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import fr.citoyende2027.core.database.model.asEntity
import fr.citoyende2027.core.database.model.coverageEntities
import fr.citoyende2027.core.database.model.themeEntities
import fr.citoyende2027.core.testing.FictionalCandidates
import kotlin.system.measureNanoTime
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner

/**
 * Room budget of AGENTS.md §4 (< 50 ms) on the heaviest screen query, a candidate's votes with their
 * themes. Robolectric's SQLite is far slower than a device's, so wall-clock time is only reported
 * here (the budget itself is measured on a device, docs/publication-checklist.md); what is asserted is
 * that both statements Room runs go through an index instead of scanning whole tables.
 */
@RunWith(RobolectricTestRunner::class)
class QueryBudgetTest {
    private val database = Room.inMemoryDatabaseBuilder(
        ApplicationProvider.getApplicationContext(),
        CitoyenDatabase::class.java,
    ).build()

    @After
    fun close() = database.close()

    @Test
    fun candidateVotesUseIndexes() {
        val candidate = FictionalCandidates.candidateA.id.value
        assertSearches(
            "SELECT * FROM votes WHERE candidate_id = ? ORDER BY ballot_date DESC, id",
            arrayOf(candidate),
            "votes",
        )
        // Statement generated by Room for the @Relation of VoteWithThemes.
        assertSearches("SELECT vote_id, theme_id FROM vote_themes WHERE vote_id IN (?)", arrayOf("v"), "vote_themes")
    }

    @Test
    fun reportsLoadTimeOfManyVotes() = runBlocking {
        val dao = database.corePackDao()
        val template = FictionalCandidates.votes.first { it.candidateId == FictionalCandidates.candidateA.id }
        val votes = List(VOTES) { i -> template.copy(id = "fictif-vote-$i", ballotId = "fictif-scrutin-$i") }
        dao.replaceCorePack(
            pack = FictionalCandidates.packInfo.asEntity(),
            candidates = FictionalCandidates.all.map { it.asEntity() },
            coverage = FictionalCandidates.all.flatMap { it.coverageEntities() },
            votes = votes.map { it.asEntity() },
            themes = FictionalCandidates.themes.map { it.asEntity() },
            voteThemes = votes.flatMap { it.themeEntities() },
        )
        val id = FictionalCandidates.candidateA.id.value
        assertEquals(VOTES, dao.observeVotes(id).first().size)
        val times = List(9) { measureNanoTime { dao.observeVotes(id).first() } / 1_000_000.0 }.sorted()
        println("Room (Robolectric): median %.1f ms to load $VOTES votes with themes".format(times[times.size / 2]))
    }

    private fun assertSearches(sql: String, args: Array<Any?>, table: String) {
        val plan = database.openHelper.readableDatabase.query("EXPLAIN QUERY PLAN $sql", args).use { cursor ->
            buildList { while (cursor.moveToNext()) add(cursor.getString(cursor.getColumnIndexOrThrow("detail"))) }
        }
        // Older SQLite versions write "SEARCH TABLE votes …"; a full scan is "SCAN [TABLE] votes" with no index.
        val search = Regex("^SEARCH (TABLE )?$table ")
        val fullScan = Regex("^SCAN (TABLE )?$table$")
        assertTrue("Plan of '$sql': $plan", plan.any(search::containsMatchIn))
        assertTrue("Plan of '$sql': $plan", plan.none(fullScan::containsMatchIn))
    }

    private companion object {
        const val VOTES = 5_000
    }
}
